def write_parquet_atomic(path: Path, rows: list[dict], columns: list[str] | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + f".{os.getpid()}.tmp")
    pd.DataFrame(rows, columns=columns).to_parquet(temp, index=False)
    os.replace(temp, path)


def export_partial(workdir: Path, selection: dict, tasks: list[dict]) -> dict:
    results_dir = workdir / "runs"
    rows = []
    for task in tasks:
        path = results_dir / f"{task['run_id']}.json"
        if path.exists():
            rows.append(json.loads(path.read_text()))
    write_parquet_atomic(workdir / "algorithm_runs.parquet", rows, RUN_COLUMNS)
    anytime = [{"run_id": row["run_id"], "instance_id": row["instance_id"], "seed": row["seed"],
                "iteration_budget": row["iteration_budget"], "semantics": "independent_fresh_run",
                "better_seed_objective": row["better_seed_objective"], "final_objective": row["objective_weight"],
                "accepted_improving_moves": row["accepted_improving_moves"], "best_iteration": row["best_iteration"],
                "time_to_best_seconds_after_initialization": row["time_to_best_seconds_after_initialization"],
                "iterations_executed": row["iterations_executed"], "status": row["status"]}
               for row in rows if row["algorithm"] == "ipsns"]
    write_parquet_atomic(workdir / "anytime_metrics.parquet", anytime,
                         ["run_id", "instance_id", "seed", "iteration_budget", "semantics", "better_seed_objective",
                          "final_objective", "accepted_improving_moves", "best_iteration",
                          "time_to_best_seconds_after_initialization", "iterations_executed", "status"])
    groups = {}
    for row in rows:
        key = (row["family"], row["n_vertices"], row["algorithm"], row["iteration_budget"])
        group = groups.setdefault(key, {"family": key[0], "n_vertices": key[1], "algorithm": key[2],
                                        "iteration_budget": key[3], "executed": 0, "validated": 0,
                                        "failed": 0, "objective_sum": 0.0})
        group["executed"] += 1
        if row["status"] == "PASS":
            group["validated"] += 1
            group["objective_sum"] += row["objective_weight"]
        else:
            group["failed"] += 1
    summary_groups = []
    for group in groups.values():
        group["objective_mean_validated"] = group.pop("objective_sum") / group["validated"] if group["validated"] else None
        summary_groups.append(group)
    summary = {"status": "COMPLETE" if len(rows) == len(tasks) and all(r["status"] == "PASS" for r in rows) else "INCOMPLETE",
               "expected_runs": len(tasks), "recorded_runs": len(rows), "validated_runs": sum(r["status"] == "PASS" for r in rows),
               "failed_or_timeout_runs": sum(r["status"] not in ("PASS", "INTERRUPTED") for r in rows),
               "groups": summary_groups, "updated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    atomic_json(workdir / "summary.json", summary)
    return summary

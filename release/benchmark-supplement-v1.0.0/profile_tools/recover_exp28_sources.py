"""Retrieve hash-pinned empirical inputs and reproduce the original four views.

Python standard library only. No optimization, alternative source, or graph
substitution is permitted. Upstream inputs/derived graphs are not redistributed.
"""
from __future__ import annotations

import csv
import gzip
import hashlib
import io
import json
import urllib.request
import zipfile
from collections import Counter, defaultdict
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def fetch(source, directory):
    path = directory / source['filename']
    with urllib.request.urlopen(source['url'], timeout=60) as response:
        content = response.read()
    if digest(content) != source['sha256']:
        raise ValueError('pinned upstream bytes changed: ' + source['filename'])
    path.write_bytes(content)
    return content


def largest_scc(vertices, edges):
    """Iterative Kosaraju; deterministic EXP05 size/lexicographic tie rule."""
    adj, rev = defaultdict(list), defaultdict(list)
    for u, v in edges:
        adj[u].append(v)
        rev[v].append(u)
    seen, finish = set(), []
    for root in sorted(vertices):
        if root in seen:
            continue
        seen.add(root)
        stack = [(root, iter(adj[root]))]
        while stack:
            u, children = stack[-1]
            v = next(children, None)
            if v is None:
                finish.append(u)
                stack.pop()
            elif v not in seen:
                seen.add(v)
                stack.append((v, iter(adj[v])))
    seen, components = set(), []
    for root in reversed(finish):
        if root in seen:
            continue
        component, todo = set(), [root]
        seen.add(root)
        while todo:
            u = todo.pop()
            component.add(u)
            for v in rev[u]:
                if v not in seen:
                    seen.add(v)
                    todo.append(v)
        if len(component) > 1:
            components.append(component)
    return min(components, key=lambda c: (-len(c), tuple(sorted(c))))


def transform(kind, blobs):
    if kind in ('college', 'email'):
        rows = [tuple(map(int, s.split())) for s in gzip.decompress(blobs[0]).decode().splitlines()
                if s.strip() and not s.startswith('#')]
        if kind == 'college':
            cutoff = min(r[2] for r in rows) + 90 * 86400
            rows = [r for r in rows if r[2] <= cutoff]
        vertices = {v for row in rows for v in row[:2]}
        edges = Counter((r[0], r[1]) for r in rows if r[0] != r[1])
        if kind == 'email':
            edges = Counter({edge: 1 for edge in edges})
            vertices = largest_scc(vertices, edges)
            edges = Counter({(u, v): w for (u, v), w in edges.items() if u in vertices and v in vertices})
    elif kind == 'exiobase':
        with zipfile.ZipFile(io.BytesIO(blobs[0])) as archive:
            words = list(map(int, archive.read('exiobase/os300/os300_us_2022_n300').split()))
        n, values = words[0], words[1:]
        if len(values) != n * n or any(w < 0 for w in values):
            raise ValueError('invalid matrix')
        vertices = set(range(1, n + 1))
        edges = Counter({(i + 1, j + 1): values[i*n+j] for i in range(n) for j in range(n)
                         if i != j and values[i*n+j] > 0})
    elif kind == 'openflights':
        airports = {}
        for row in csv.reader(io.StringIO(blobs[1].decode())):
            if len(row) < 4:
                raise ValueError('malformed airport row')
            if row[0].isdigit():
                if row[0] in airports:
                    raise ValueError('duplicate airport ID')
                airports[row[0]] = row[3]
        edges = Counter()
        for row in csv.reader(io.StringIO(blobs[0].decode())):
            if len(row) != 9:
                raise ValueError('malformed route row')
            if (row[3].isdigit() and row[5].isdigit() and row[3] in airports and row[5] in airports
                    and airports[row[3]] == airports[row[5]] == 'United States'
                    and row[7] == '0' and row[3] != row[5]):
                edges[(f'airport:{int(row[3])}', f'airport:{int(row[5])}')] += 1
        vertices = {v for edge in edges for v in edge}
    else:
        raise ValueError('unknown transformation')
    index = {v: i for i, v in enumerate(sorted(vertices), 1)}
    arcs = sorted((index[u], index[v], w) for (u, v), w in edges.items())
    header = (f'p graph {len(vertices)} {len(arcs)}\n' if kind == 'openflights' else
              f'c generated by mwfas_data.generation\np sp {len(vertices)} {len(arcs)}\n')
    return (header + ''.join(f'a {u} {v} {w}\n' for u, v, w in arcs)).encode()


def recover(specification, directory, graphs):
    directory.mkdir(parents=True, exist_ok=False)
    receipts = []
    for source in specification:
        try:
            blobs = [fetch(item, directory) for item in source['files']]
            content = transform(source['transformation'], blobs)
            if digest(content) != source['graph_sha256']:
                raise ValueError('transformed graph differs from exact original DIMACS')
            (graphs / (source['graph_id'] + '.d')).write_bytes(content)
            receipts.append({'graph_id': source['graph_id'], 'status': 'PASS',
                             'identity': 'BYTE_IDENTICAL', 'sha256': digest(content),
                             'inputs': source['files']})
        except Exception as error:
            receipts.append({'graph_id': source['graph_id'], 'status': 'NOT VERIFIABLE',
                             'error': str(error), 'inputs': source['files']})
    (directory / 'recovery.json').write_text(json.dumps(receipts, indent=2) + '\n')
    return receipts


if __name__ == '__main__':
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('specification', type=Path)
    p.add_argument('directory', type=Path)
    a = p.parse_args()
    graphs = a.directory / 'graphs'
    graphs.mkdir(parents=True, exist_ok=False)
    result = recover(json.loads(a.specification.read_text()), a.directory / 'upstream', graphs)
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if all(r['status'] == 'PASS' for r in result) else 2)

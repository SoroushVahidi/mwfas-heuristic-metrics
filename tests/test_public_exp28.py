"""Adversarial checks for public source reconstruction and order validation."""
import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1] / 'release/public_reproducibility'


def module(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / (name + '.py'))
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


def test_scc_selection_includes_isolates_and_breaks_equal_size_ties():
    source = module('recover_exp28_sources')
    assert source.largest_scc({0, 1, 2, 3, 4}, [(1, 2), (2, 1), (3, 4), (4, 3)]) == {1, 2}


def test_college_inclusive_cutoff_preserves_message_multiplicity():
    import gzip
    source = module('recover_exp28_sources')
    data = gzip.compress(b'9 2 0\n9 2 7776000\n2 9 7776001\n')
    assert source.transform('college', [data]) == b'c generated by mwfas_data.generation\np sp 2 1\na 2 1 2\n'


def test_upstream_hash_mismatch_cannot_be_accepted(tmp_path, monkeypatch):
    import io
    source = module('recover_exp28_sources')
    monkeypatch.setattr(source.urllib.request, 'urlopen', lambda *a, **kw: io.BytesIO(b'changed'))
    with pytest.raises(ValueError, match='pinned upstream bytes changed'):
        source.fetch({'filename': 'source', 'url': 'https://example.invalid', 'sha256': '0'*64}, tmp_path)
    assert not (tmp_path/'source').exists()


def test_order_validation_rejects_duplicates_and_scores_weighted_cycle(tmp_path):
    check = module('exp28_checks')
    order = tmp_path/'order.txt'
    order.write_text('0 1 2\n')
    assert check.score(order, 'xiong_single', 3, [(1, 2, 7), (2, 3, 2), (3, 1, 11)]) == 11
    order.write_text('0 1 1\n')
    with pytest.raises(ValueError, match='incomplete permutation'):
        check.score(order, 'xiong_single', 3, [(1, 2, 7), (2, 3, 2), (3, 1, 11)])


def test_graph_check_rejects_parallel_arcs_before_canonical_hash(tmp_path):
    import hashlib
    check = module('exp28_checks')
    graph = tmp_path/'graph.d'
    graph.write_text('p sp 2 2\na 1 2 3\na 1 2 4\n')
    meta = {'dimacs_sha256': hashlib.sha256(graph.read_bytes()).hexdigest(), 'n': 2, 'm': 2}
    with pytest.raises(ValueError, match='invalid active arcs'):
        check.graph(graph, meta)
